#include "indiccrypt/crypto/kdf.hpp"

#include <cassert>
#include <span>
#include <vector>

namespace {

using Byte = indiccrypt::crypto::Byte;

bool equal(
    std::span<const Byte> lhs,
    std::span<const Byte> rhs
) {
    if (lhs.size() != rhs.size()) {
        return false;
    }

    for (std::size_t i = 0; i < lhs.size(); ++i) {
        if (lhs[i] != rhs[i]) {
            return false;
        }
    }

    return true;
}

} // namespace

int main() {
    using namespace indiccrypt::crypto;

    const Key ikm({
        0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b
    });

    const std::vector<Byte> salt = {
        0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b,
        0x0c
    };

    const std::vector<Byte> info = {
        0xf0, 0xf1, 0xf2, 0xf3,
        0xf4, 0xf5, 0xf6, 0xf7,
        0xf8, 0xf9
    };

    const Key expected({
        0x3c, 0xb2, 0x5f, 0x25,
        0xfa, 0xac, 0xd5, 0x7a,
        0x90, 0x43, 0x4f, 0x64,
        0xd0, 0x36, 0x2f, 0x2a,
        0x2d, 0x2d, 0x0a, 0x90,
        0xcf, 0x1a, 0x5a, 0x4c,
        0x5d, 0xb0, 0x2d, 0x56,
        0xec, 0xc4, 0xc5, 0xbf,
        0x34, 0x00, 0x72, 0x08,
        0xd5, 0xb8, 0x87, 0x18,
        0x58, 0x65
    });

    const Key actual =
        KeyDerivation::hkdfSha256(
            ikm.bytes(),
            salt,
            info,
            42
        );

    assert(equal(
        actual.bytes(),
        expected.bytes()
    ));

    return 0;
}